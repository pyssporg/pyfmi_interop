"""C++ source generation for one realtime model runtime.

The generator turns a :class:`~pyfmi_distributed.ir.ModelDefinition` into a
small, self-contained CMake project.  Every emitted byte is derived from the
IR: signals are sorted by value reference, bindings by signal/transport/channel,
and no timestamp or ambient value is written.  Two generations of the same IR
therefore produce byte-identical trees.

String signals are stored in ``std::array<char, capacity>`` members.  The
capacity is part of the IR and the array lives inside the model object, so the
step loop never allocates for string storage; ``read()`` still copies into the
``std::string`` carried by :struct:`pyfmi_distributed::Value` because that is
the runtime ABI.
"""

from __future__ import annotations

from pathlib import Path

from ..ir import DataType, ModelDefinition, Signal, fingerprint, write_model_json
from .cmake import render_cmake

__all__ = ["generate_model"]

_HEADER = "// Generated by pyfmi-distributed. Do not edit by hand.\n"


def generate_model(model: ModelDefinition, out_dir: str | Path) -> Path:
    """Write the complete C++ source tree for ``model`` into ``out_dir``."""

    model.validate()
    _check_types(model)

    target = Path(out_dir)
    target.mkdir(parents=True, exist_ok=True)

    _write(target / "model_runtime.hpp", _render_runtime_hpp(model))
    _write(target / "model_runtime.cpp", _render_runtime_cpp(model))
    _write(target / "model_impl.hpp", _render_model_impl(model))
    _write(target / "bindings.cpp", _render_bindings(model))
    _write(target / "CMakeLists.txt", _CMAKELISTS_PREFIX + render_cmake(model))
    write_model_json(model, target / "model.json")
    return target


def _write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")


def _ordered_signals(model: ModelDefinition) -> tuple[Signal, ...]:
    return tuple(sorted(model.signals, key=lambda item: item.value_reference))


def _check_types(model: ModelDefinition) -> None:
    for signal in model.signals:
        if signal.data_type is DataType.STRING and signal.capacity <= 0:
            raise ValueError(f"{signal.name}: string signals require a positive capacity")
        if signal.initial is not None and signal.data_type is DataType.REAL:
            try:
                float(signal.initial)  # type: ignore[arg-type]
            except (TypeError, ValueError) as error:
                raise ValueError(f"{signal.name}: real initial value is not numeric") from error


def _sanitize(name: str) -> str:
    cleaned = "".join(
        char if char.isascii() and (char.isalnum() or char == "_") else "_" for char in name
    )
    if not cleaned or cleaned[0].isdigit():
        cleaned = "_" + cleaned
    return cleaned


def _member(signal: Signal) -> str:
    return f"m_vr{signal.value_reference}_{_sanitize(signal.name)}"


def _float(value: float) -> str:
    number = float(value)
    if number != number or number in (float("inf"), float("-inf")):
        raise ValueError(f"non-finite floating point value: {number!r}")
    return repr(number)


def _cpp_type(signal: Signal) -> str:
    if signal.data_type is DataType.REAL:
        return "double"
    if signal.data_type is DataType.INTEGER:
        return "std::int32_t"
    if signal.data_type is DataType.BOOLEAN:
        return "bool"
    return f"std::array<char, {signal.capacity}>"


def _initial_declaration(signal: Signal) -> str:
    member = _member(signal)
    if signal.data_type is DataType.REAL:
        return f"    double {member} = {_float(signal.initial or 0.0)};"
    if signal.data_type is DataType.INTEGER:
        return f"    std::int32_t {member} = {int(signal.initial or 0)};"
    if signal.data_type is DataType.BOOLEAN:
        return f"    bool {member} = {'true' if _bool_initial(signal.initial) else 'false'};"
    return f"    std::array<char, {signal.capacity}> {member}{{}};"


def _bool_initial(value: object) -> bool:
    if isinstance(value, str):
        return value.strip().lower() in {"1", "true", "yes", "on"}
    return bool(value)


def _reset_statement(signal: Signal) -> str:
    member = _member(signal)
    if signal.data_type is DataType.REAL:
        return f"    {member} = {_float(signal.initial or 0.0)};"
    if signal.data_type is DataType.INTEGER:
        return f"    {member} = {int(signal.initial or 0)};"
    if signal.data_type is DataType.BOOLEAN:
        return f"    {member} = {'true' if _bool_initial(signal.initial) else 'false'};"
    text = "" if signal.initial is None else str(signal.initial)
    return (
        f"    {member}.fill('\\0');\n"
        f"    copy_bounded({member}.data(), {member}.size(), {_string_literal(text)});"
    )


def _string_literal(value: str) -> str:
    chunks: list[str] = []
    for byte in value.encode("utf-8"):
        char = chr(byte)
        if char == "\\":
            chunks.append("\\\\")
        elif char == '"':
            chunks.append('\\"')
        elif char == "\n":
            chunks.append("\\n")
        elif char == "\r":
            chunks.append("\\r")
        elif char == "\t":
            chunks.append("\\t")
        elif 32 <= byte < 127:
            chunks.append(char)
        else:
            # Octal escapes are always three digits, so a following digit cannot
            # extend the escape.  This keeps non-ASCII initial values stable.
            chunks.append(f"\\{byte:03o}")
    return '"' + "".join(chunks) + '"'


def _value_expression(signal: Signal) -> str:
    member = _member(signal)
    if signal.data_type is DataType.REAL:
        return f"pyfmi_distributed::Value::make_real({member})"
    if signal.data_type is DataType.INTEGER:
        return f"pyfmi_distributed::Value::make_integer({member})"
    if signal.data_type is DataType.BOOLEAN:
        return f"pyfmi_distributed::Value::make_boolean({member})"
    return f"pyfmi_distributed::Value::make_string({member}.data())"


def _cpp_data_type(signal: Signal) -> str:
    return f"pyfmi_distributed::DataType::{signal.data_type.value.capitalize()}"


def _cpp_direction(signal: Signal) -> str:
    return f"pyfmi_distributed::Direction::{signal.direction.value.capitalize()}"


def _render_runtime_hpp(model: ModelDefinition) -> str:
    signals = _ordered_signals(model)
    members = "\n".join(_initial_declaration(signal) for signal in signals)
    if not members:
        members = "    // This model has no signals.\n"
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "//\n"
        + "// String signals are stored in fixed std::array<char, capacity> members so\n"
        + "// the step loop owns their storage and never allocates for it.\n"
        + "#pragma once\n"
        + "\n"
        + "#include <array>\n"
        + "#include <cstddef>\n"
        + "#include <cstdint>\n"
        + "#include <cstring>\n"
        + "#include <string_view>\n"
        + "#include <vector>\n"
        + "\n"
        + '#include "pyfmi_distributed/runtime/model_runtime.hpp"\n'
        + "\n"
        + "namespace {\n"
        + "\n"
        + "inline std::size_t copy_bounded(char* target, std::size_t capacity, "
        + "std::string_view text) {\n"
        + "    if (capacity == 0u) {\n"
        + "        return 0u;\n"
        + "    }\n"
        + "    const std::size_t count = text.size() < capacity - 1u\n"
        + "                                ? text.size() : capacity - 1u;\n"
        + "    std::memcpy(target, text.data(), count);\n"
        + "    target[count] = '\\0';\n"
        + "    return count;\n"
        + "}\n"
        + "\n"
        + "}  // namespace\n"
        + "\n"
        + "// The user_step hook is defined in model_impl.hpp and may edit these public\n"
        + "// members.  There is one typed member per signal.\n"
        + "class GeneratedModelRuntime final : public pyfmi_distributed::ModelRuntime {\n"
        + "public:\n"
        + "    GeneratedModelRuntime() = default;\n"
        + "\n"
        + "    const std::vector<pyfmi_distributed::SignalDescriptor>& signals() "
        + "const override;\n"
        + "    void reset() override;\n"
        + "    void step(double time, double step_size) override;\n"
        + "    bool read(std::uint32_t value_reference, "
        + "pyfmi_distributed::Value& out) const override;\n"
        + "    bool write(std::uint32_t value_reference, "
        + "const pyfmi_distributed::Value& value) override;\n"
        + "    void publish(pyfmi_distributed::Sample& sample) const override;\n"
        + "    void consume(const pyfmi_distributed::Sample& sample) override;\n"
        + "\n"
        + members
        + "\n"
        + "    double m_simulation_time = 0.0;\n"
        + "};\n"
    )


def _render_runtime_cpp(model: ModelDefinition) -> str:
    signals = _ordered_signals(model)
    descriptors = ",\n".join(
        "        pyfmi_distributed::SignalDescriptor{"
        + f"{_string_literal(signal.name)}, {signal.value_reference}u, "
        + f"{_cpp_data_type(signal)}, {_cpp_direction(signal)}, "
        + f"{_float(signal.period_s or 0.0)}, {signal.capacity}u"
        + "}"
        for signal in signals
    )
    if not descriptors:
        descriptors = "    "
    reset_lines = "\n".join(_reset_statement(signal) for signal in signals)
    if not reset_lines:
        reset_lines = "    (void)0;"
    read_cases = "\n".join(
        _read_case(signal) for signal in signals if signal.direction.readable
    )
    write_cases = "\n".join(
        _write_case(signal) for signal in signals if signal.direction.writable
    )
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + '#include "model_impl.hpp"\n'
        + "\n"
        + "namespace {\n"
        + "\n"
        + "const std::vector<pyfmi_distributed::SignalDescriptor>& model_signals() {\n"
        + "    static const std::vector<pyfmi_distributed::SignalDescriptor> signals = {\n"
        + descriptors
        + "\n"
        + "    };\n"
        + "    return signals;\n"
        + "}\n"
        + "\n"
        + "}  // namespace\n"
        + "\n"
        + "const std::vector<pyfmi_distributed::SignalDescriptor>& "
        + "GeneratedModelRuntime::signals() const {\n"
        + "    return model_signals();\n"
        + "}\n"
        + "\n"
        + "void GeneratedModelRuntime::reset() {\n"
        + reset_lines
        + "\n"
        + "    m_simulation_time = 0.0;\n"
        + "}\n"
        + "\n"
        + "void GeneratedModelRuntime::step(double time, double step_size) {\n"
        + "    m_simulation_time = time;\n"
        + "    user_step(*this, time, step_size);\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::read(std::uint32_t value_reference, "
        + "pyfmi_distributed::Value& out) const {\n"
        + "    switch (value_reference) {\n"
        + read_cases
        + "\n"
        + "        default:\n"
        + "            return false;\n"
        + "    }\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::write(std::uint32_t value_reference, "
        + "const pyfmi_distributed::Value& value) {\n"
        + "    switch (value_reference) {\n"
        + write_cases
        + "\n"
        + "        default:\n"
        + "            return false;\n"
        + "    }\n"
        + "}\n"
        + "\n"
        + 'extern "C" pyfmi_distributed::ModelRuntime* pyfmi_distributed_create_model() {\n'
        + "    return new GeneratedModelRuntime();\n"
        + "}\n"
        + "\n"
        + 'extern "C" void pyfmi_distributed_destroy_model('
        + "pyfmi_distributed::ModelRuntime* model) {\n"
        + "    delete model;\n"
        + "}\n"
    )


def _read_case(signal: Signal) -> str:
    return (
        f"        case {signal.value_reference}u:\n"
        + f"            out = {_value_expression(signal)};\n"
        + "            return true;"
    )


def _write_case(signal: Signal) -> str:
    member = _member(signal)
    if signal.data_type is DataType.STRING:
        assignment = (
            f"            copy_bounded({member}.data(), {member}.size(), "
            "value.string_value);"
        )
    elif signal.data_type is DataType.REAL:
        assignment = f"            {member} = value.real_value;"
    elif signal.data_type is DataType.INTEGER:
        assignment = f"            {member} = value.integer_value;"
    else:
        assignment = f"            {member} = value.boolean_value;"
    return (
        f"        case {signal.value_reference}u:\n"
        + f"            if (value.type != {_cpp_data_type(signal)}) {{\n"
        + "                return false;\n"
        + "            }\n"
        + assignment
        + "\n"
        + "            return true;"
    )


def _render_model_impl(model: ModelDefinition) -> str:
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + "//\n"
        + "// User hook.  The SysML input defines the signal interface, not the\n"
        + "// equations, so the default implementation is deliberately empty.  Edit\n"
        + "// this file (only this file) to implement the model behaviour.\n"
        + "#pragma once\n"
        + "\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + "inline void user_step(GeneratedModelRuntime& model, double time, double dt) {\n"
        + "    (void)model;\n"
        + "    (void)time;\n"
        + "    (void)dt;\n"
        + "    // TODO: implement the model equations.  Read and write the typed\n"
        + "    // members declared in model_runtime.hpp.\n"
        + "}\n"
    )


def _render_bindings(model: ModelDefinition) -> str:
    signals = _ordered_signals(model)
    bound_names = {binding.signal for binding in model.bindings}
    publish_signals = [
        signal
        for signal in signals
        if signal.name in bound_names and signal.direction.readable
    ]
    consume_signals = [
        signal
        for signal in signals
        if signal.name in bound_names and signal.direction.writable
    ]
    publish_lines = "\n".join(_publish_statement(signal) for signal in publish_signals)
    consume_lines = "\n".join(_consume_statement(signal) for signal in consume_signals)
    if not publish_lines:
        publish_lines = "    (void)sample;"
    if not consume_lines:
        consume_lines = "    (void)sample;"
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "//\n"
        + "// Only signals with a TransportBinding are packed or unpacked here.  The\n"
        + "// Sample frame is indexed directly by value reference and is preallocated\n"
        + "// by the scheduler.\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + "void GeneratedModelRuntime::publish(pyfmi_distributed::Sample& sample) const {\n"
        + "    sample.simulation_time = m_simulation_time;\n"
        + publish_lines
        + "\n"
        + "}\n"
        + "\n"
        + "void GeneratedModelRuntime::consume(const pyfmi_distributed::Sample& sample) {\n"
        + consume_lines
        + "\n"
        + "}\n"
    )


def _publish_statement(signal: Signal) -> str:
    vr = signal.value_reference
    return (
        f"    if ({vr}u < sample.values.size() && {vr}u < sample.valid.size()) {{\n"
        + f"        sample.values[{vr}u] = {_value_expression(signal)};\n"
        + f"        sample.valid[{vr}u] = 1u;\n"
        + "    }"
    )


def _consume_statement(signal: Signal) -> str:
    vr = signal.value_reference
    member = _member(signal)
    if signal.data_type is DataType.STRING:
        assignment = (
            f"            copy_bounded({member}.data(), {member}.size(), "
            f"sample.values[{vr}u].string_value);"
        )
    elif signal.data_type is DataType.REAL:
        assignment = f"            {member} = sample.values[{vr}u].real_value;"
    elif signal.data_type is DataType.INTEGER:
        assignment = f"            {member} = sample.values[{vr}u].integer_value;"
    else:
        assignment = f"            {member} = sample.values[{vr}u].boolean_value;"
    return (
        f"    if ({vr}u < sample.values.size() && {vr}u < sample.valid.size()\n"
        + f"        && sample.is_valid({vr}u)\n"
        + f"        && sample.values[{vr}u].type == {_cpp_data_type(signal)}) {{\n"
        + assignment
        + "\n"
        + "    }"
    )


_CMAKELISTS_PREFIX = "# Generated by pyfmi-distributed. Do not edit by hand.\n"
