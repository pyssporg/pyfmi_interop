"""C++ source generation for one realtime model runtime.

The generator turns a :class:`~pyfmi_interop.ir.ModelDefinition` into a
small, self-contained CMake project.  Every emitted byte is derived from the
IR: signals are sorted by value reference, and no timestamp or ambient value is
written.  Two generations of the same IR therefore produce byte-identical
trees.

String signals are stored in ``std::array<char, capacity>`` members.  The
capacity is part of the IR and the array lives inside the model object, so the
step loop never allocates for string storage; ``read()`` still copies into the
``std::string`` carried by :struct:`pyfmi_interop::Value` because that is
the runtime ABI.

The payload codec is a serialization backend concern: ``protobuf`` emits its
own ``model_wire.cpp`` and conformance executable, ``packed`` currently emits
the Python encoder only, and ``opaque`` emits no codec at all.
"""

from __future__ import annotations

from dataclasses import replace
from pathlib import Path

from ..ir import DataType, Direction, ModelDefinition, Signal, fingerprint, write_model_json
from ..roles import resolve_role
from ..serialization import get as get_serialization
from ..serialization.naming import (
    bool_initial,
    cpp_data_type,
    cpp_direction,
    float_literal,
    member_name,
    ordered_signals,
    string_literal,
    value_expression,
    wire_signals,
)
from .cmake import render_cmake

__all__ = ["generate_model"]

_HEADER = "// Generated by pyfmi-interop. Do not edit by hand.\n"


def generate_model(
    model: ModelDefinition,
    out_dir: str | Path,
    *,
    serialization: str = "protobuf",
    role: str | None = None,
    fmi_layer: str = "interop",
    sysml_source: object | None = None,
    composition: str | None = None,
    component: str | None = None,
    prefix: str | None = None,
) -> Path:
    """Write the complete C++ source tree for ``model`` into ``out_dir``.

    ``serialization`` selects the payload backend.  ``role`` may narrow the
    role derived from FMI causality; widening it raises :class:`ValueError`.

    ``fmi_layer`` selects who owns the FMI 2.0 C interface.  The default
    ``"interop"`` keeps this repository's facade.  ``"psysml2"`` delegates the
    FMI interface, headers and ``modelDescription.xml`` to ``pyfmi_sysml2``
    and supplies the model hooks here; it needs ``sysml_source=`` (a SysML path
    or an already loaded ``Architecture``) and cannot be used for a JSON
    ``model.json`` input that has no architecture behind it.
    """

    if fmi_layer == "psysml2":
        from ..psysml2 import generate_adapter_model

        return generate_adapter_model(
            model,
            out_dir,
            source=sysml_source,
            serialization=serialization,
            role=role,
            composition=composition,
            component=component,
            prefix=prefix,
        )
    if fmi_layer != "interop":
        raise ValueError(
            f"unknown fmi_layer {fmi_layer!r}; expected 'interop' or 'psysml2'"
        )

    model.validate()
    _check_types(model)
    resolved_role = resolve_role(model, role)
    backend = get_serialization(serialization)
    effective = replace(
        model,
        role=resolved_role,
        serialization=backend.name,
    )

    target = Path(out_dir)
    target.mkdir(parents=True, exist_ok=True)

    _write(target / "model_runtime.hpp", _render_runtime_hpp(effective))
    _write(target / "model_runtime.cpp", _render_runtime_cpp(effective))
    _write(target / "model_impl.hpp", _render_model_impl(effective))
    _write(target / "bindings.cpp", _render_bindings(effective))
    _write(
        target / "CMakeLists.txt",
        _CMAKELISTS_PREFIX + render_cmake(effective, backend.name),
    )
    write_model_json(effective, target / "model.json")
    backend.emit_schema(effective, target)
    backend.generate_codec(effective, target, resolved_role)
    return target


def _write(path: Path, text: str) -> None:
    path.write_text(text, encoding="utf-8", newline="\n")


def _check_types(model: ModelDefinition) -> None:
    for signal in model.signals:
        if signal.data_type is DataType.STRING and signal.capacity <= 0:
            raise ValueError(f"{signal.name}: string signals require a positive capacity")
        if signal.initial is not None and signal.data_type is DataType.REAL:
            try:
                float(signal.initial)  # type: ignore[arg-type]
            except (TypeError, ValueError) as error:
                raise ValueError(
                    f"{signal.name}: real initial value is not numeric"
                ) from error


def _initial_declaration(signal: Signal) -> str:
    member = member_name(signal)
    if signal.data_type is DataType.REAL:
        return f"    double {member} = {float_literal(signal.initial or 0.0)};"
    if signal.data_type is DataType.INTEGER:
        return f"    std::int32_t {member} = {int(signal.initial or 0)};"
    if signal.data_type is DataType.BOOLEAN:
        return (
            f"    bool {member} = "
            f"{'true' if bool_initial(signal.initial) else 'false'};"
        )
    return f"    std::array<char, {signal.capacity}> {member}{{}};"


def _reset_statement(signal: Signal) -> str:
    member = member_name(signal)
    if signal.data_type is DataType.REAL:
        return f"    {member} = {float_literal(signal.initial or 0.0)};"
    if signal.data_type is DataType.INTEGER:
        return f"    {member} = {int(signal.initial or 0)};"
    if signal.data_type is DataType.BOOLEAN:
        return (
            f"    {member} = "
            f"{'true' if bool_initial(signal.initial) else 'false'};"
        )
    text = "" if signal.initial is None else str(signal.initial)
    return (
        f"    {member}.fill('\\0');\n"
        f"    copy_bounded({member}.data(), {member}.size(), {string_literal(text)});"
    )


def _exposes_codec(model: ModelDefinition) -> bool:
    """A generated model advertises its codec only when it has a transport role."""

    return (
        model.role not in (None, "none")
        and model.serialization in {"packed", "protobuf"}
    )


def _render_runtime_hpp(model: ModelDefinition) -> str:
    signals = ordered_signals(model)
    members = "\n".join(_initial_declaration(signal) for signal in signals)
    if not members:
        members = "    // This model has no signals.\n"
    parameter_members = ""
    if any(signal.direction is Direction.PARAMETER for signal in signals):
        parameter_members = (
            "\n"
            "    // Name-based deployment parameter lookup; the runtime resolves\n"
            "    // the transport before initialization without knowing the port name.\n"
            "    const char* interop_parameter_string(\n"
            "        const char* name, std::size_t* length) const override;\n"
            "    bool interop_parameter_integer(\n"
            "        const char* name, std::int32_t* value) const override;\n"
        )
    exposes = _exposes_codec(model)
    codec_prelude = ""
    wire_members = ""
    if exposes:
        codec_prelude = (
            "class GeneratedModelRuntime;\n"
            "\n"
            "// The model's codec view: the FMI facade receives this interface and\n"
            "// never knows the payload schema.\n"
            "class GeneratedWireCodec final : public pyfmi_interop::WireModelCodec {\n"
            "public:\n"
            "    explicit GeneratedWireCodec(GeneratedModelRuntime& model)\n"
            "        : m_model(model) {}\n"
            "\n"
            "    pyfmi_interop::TransportRole transport_role() const override;\n"
            "    pyfmi_interop::wire::PayloadFormat payload_format() const override;\n"
            "    bool wire_model_id(\n"
            "        std::array<std::uint8_t, "
            "pyfmi_interop::wire::kModelIdSize>& out) const override;\n"
            "    bool encode_wire_payload(std::string& payload,\n"
            "                             std::string& error) const override;\n"
            "    bool decode_wire_payload(std::string_view payload,\n"
            "                             std::string& error) override;\n"
            "\n"
            "private:\n"
            "    GeneratedModelRuntime& m_model;\n"
            "};\n"
            "\n"
        )
        wire_members = (
            "    pyfmi_interop::WireModelCodec* wire_codec() noexcept override {\n"
            "        return &m_wire_codec;\n"
            "    }\n"
            "    GeneratedWireCodec m_wire_codec{*this};\n"
        )
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "//\n"
        + "// String signals are stored in fixed std::array<char, capacity> members so\n"
        + "// the step loop owns their storage and never allocates for it.\n"
        + "#pragma once\n"
        + "\n"
        + "#include <array>\n"
        + "#include <cstddef>\n"
        + "#include <cstdint>\n"
        + "#include <cstring>\n"
        + "#include <string>\n"
        + "#include <string_view>\n"
        + "#include <vector>\n"
        + "\n"
        + '#include "pyfmi_interop/runtime/model_runtime.hpp"\n'
        + "\n"
        + "namespace {\n"
        + "\n"
        + "inline std::size_t copy_bounded(char* target, std::size_t capacity, "
        + "std::string_view text) {\n"
        + "    if (capacity == 0u) {\n"
        + "        return 0u;\n"
        + "    }\n"
        + "    const std::size_t count = text.size() < capacity - 1u\n"
        + "                                ? text.size() : capacity - 1u;\n"
        + "    std::memcpy(target, text.data(), count);\n"
        + "    target[count] = '\\0';\n"
        + "    return count;\n"
        + "}\n"
        + "\n"
        + "}  // namespace\n"
        + "\n"
        + codec_prelude
        + "// The user_step hook is defined in model_impl.hpp and may edit these public\n"
        + "// members.  There is one typed member per signal.\n"
        + "class GeneratedModelRuntime final : public pyfmi_interop::ModelRuntime {\n"
        + "public:\n"
        + "    GeneratedModelRuntime() { reset(); }\n"
        + "\n"
        + "    const std::vector<pyfmi_interop::SignalDescriptor>& signals() "
        + "const override;\n"
        + "    void reset() override;\n"
        + "    void step(double time, double step_size) override;\n"
        + "    bool read(std::uint32_t value_reference, "
        + "pyfmi_interop::Value& out) const override;\n"
        + "    bool write(std::uint32_t value_reference, "
        + "const pyfmi_interop::Value& value) override;\n"
        + "    void publish(pyfmi_interop::Sample& sample) const override;\n"
        + "    void consume(const pyfmi_interop::Sample& sample) override;\n"
        + wire_members
        + parameter_members
        + "\n"
        + "    // Wire hooks.  A payload backend defines these in its codec source;\n"
        + "    // the payload is the generated interface message.\n"
        + "    std::vector<std::uint8_t> encode_wire_frame(\n"
        + "        std::uint32_t instance, std::uint64_t sequence,\n"
        + "        std::uint64_t timestamp_ns, std::string& error) const;\n"
        + "    bool decode_wire_frame(const std::vector<std::uint8_t>& frame,\n"
        + "                           std::string& error);\n"
        + "    bool encode_wire_payload(std::string& payload, std::string& error) const;\n"
        + "    bool decode_wire_payload(std::string_view payload, std::string& error);\n"
        + "\n"
        + members
        + "\n"
        + "    double m_simulation_time = 0.0;\n"
        + "};\n"
    )


def _render_runtime_cpp(model: ModelDefinition) -> str:
    signals = ordered_signals(model)
    wire = wire_signals(model)
    parameter_definitions = _render_parameter_lookups(signals)
    wire_definitions = ""
    if _exposes_codec(model):
        role = str(model.role).capitalize()
        payload_format = {
            "packed": "Packed",
            "protobuf": "Protobuf",
        }[str(model.serialization)]
        records = ", ".join(
            f"{{{signal.value_reference}u, {signal.data_type.number}u}}"
            for signal in wire
        )
        wire_definitions = (
            "pyfmi_interop::TransportRole "
            "GeneratedWireCodec::transport_role() const {\n"
            f"    return pyfmi_interop::TransportRole::{role};\n"
            "}\n"
            "\n"
            "pyfmi_interop::wire::PayloadFormat "
            "GeneratedWireCodec::payload_format() const {\n"
            f"    return pyfmi_interop::wire::PayloadFormat::{payload_format};\n"
            "}\n"
            "\n"
            "bool GeneratedWireCodec::wire_model_id(\n"
            "    std::array<std::uint8_t, pyfmi_interop::wire::kModelIdSize>& out) "
            "const {\n"
            "    out = pyfmi_interop::wire::model_id(\n"
            f"        std::string_view({string_literal(model.name)}),\n"
            "        std::vector<pyfmi_interop::wire::ModelIdSignal>{"
            + records
            + "});\n"
            "    return true;\n"
            "}\n"
            "\n"
            "bool GeneratedWireCodec::encode_wire_payload(\n"
            "    std::string& payload, std::string& error) const {\n"
            "    return m_model.encode_wire_payload(payload, error);\n"
            "}\n"
            "\n"
            "bool GeneratedWireCodec::decode_wire_payload(\n"
            "    std::string_view payload, std::string& error) {\n"
            "    return m_model.decode_wire_payload(payload, error);\n"
            "}\n"
            "\n"
        )
    descriptors = ",\n".join(
        "        pyfmi_interop::SignalDescriptor{"
        + f"{string_literal(signal.name)}, {signal.value_reference}u, "
        + f"{cpp_data_type(signal)}, {cpp_direction(signal)}, "
        + f"{float_literal(signal.period_s or 0.0)}, {signal.capacity}u"
        + "}"
        for signal in signals
    )
    if not descriptors:
        descriptors = "    "
    reset_lines = "\n".join(_reset_statement(signal) for signal in signals)
    if not reset_lines:
        reset_lines = "    (void)0;"
    read_cases = "\n".join(
        _read_case(signal) for signal in signals if signal.direction.readable
    )
    write_cases = "\n".join(
        _write_case(signal) for signal in signals if signal.direction.writable
    )
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + '#include "model_impl.hpp"\n'
        + "\n"
        + "#include <cctype>\n"
        + "\n"
        + "namespace {\n"
        + "\n"
        + "const std::vector<pyfmi_interop::SignalDescriptor>& model_signals() {\n"
        + "    static const std::vector<pyfmi_interop::SignalDescriptor> signals = {\n"
        + descriptors
        + "\n"
        + "    };\n"
        + "    return signals;\n"
        + "}\n"
        + "\n"
        + "}  // namespace\n"
        + "\n"
        + "const std::vector<pyfmi_interop::SignalDescriptor>& "
        + "GeneratedModelRuntime::signals() const {\n"
        + "    return model_signals();\n"
        + "}\n"
        + "\n"
        + "void GeneratedModelRuntime::reset() {\n"
        + reset_lines
        + "\n"
        + "    m_simulation_time = 0.0;\n"
        + "}\n"
        + "\n"
        + "void GeneratedModelRuntime::step(double time, double step_size) {\n"
        + "    m_simulation_time = time;\n"
        + "    user_step(*this, time, step_size);\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::read(std::uint32_t value_reference, "
        + "pyfmi_interop::Value& out) const {\n"
        + "    switch (value_reference) {\n"
        + read_cases
        + "\n"
        + "        default:\n"
        + "            return false;\n"
        + "    }\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::write(std::uint32_t value_reference, "
        + "const pyfmi_interop::Value& value) {\n"
        + "    switch (value_reference) {\n"
        + write_cases
        + "\n"
        + "        default:\n"
        + "            return false;\n"
        + "    }\n"
        + "}\n"
        + "\n"
        + wire_definitions
        + parameter_definitions
        + 'extern "C" pyfmi_interop::ModelRuntime* pyfmi_interop_create_model() {\n'
        + "    return new GeneratedModelRuntime();\n"
        + "}\n"
        + "\n"
        + 'extern "C" void pyfmi_interop_destroy_model('
        + "pyfmi_interop::ModelRuntime* model) {\n"
        + "    delete model;\n"
        + "}\n"
    )


def _render_parameter_lookups(signals: tuple[Signal, ...]) -> str:
    """Name-based, per-instance access to deployment parameter members.

    The runtime resolves the transport from these values before initialization.
    Matching is case-insensitive on the last dotted segment, so a parameter
    carried by a ``parameters`` port and one authored with a bare name resolve
    the same way without the runtime knowing the port name.
    """

    parameters = [
        signal for signal in signals if signal.direction is Direction.PARAMETER
    ]
    if not parameters:
        return ""

    def matches(signal: Signal) -> str:
        return (
            f'    if (parameter_key_matches(name, {string_literal(signal.name)})) {{'
        )

    string_lines = [
        matches(signal)
        + "\n"
        + "        if (length != nullptr) {\n"
        + f"            *length = std::strlen({member_name(signal)}.data());\n"
        + "        }\n"
        + f"        return {member_name(signal)}.data();\n"
        + "    }"
        for signal in parameters
        if signal.data_type is DataType.STRING
    ]
    integer_lines = [
        matches(signal)
        + "\n"
        + f"        *value = {member_name(signal)};\n"
        + "        return true;\n"
        + "    }"
        for signal in parameters
        if signal.data_type is DataType.INTEGER
    ]
    if not string_lines:
        string_lines = ["    (void)name;"]
    if not integer_lines:
        integer_lines = ["    (void)name;", "    (void)value;"]

    return (
        "namespace {\n"
        "\n"
        "bool parameter_key_matches(const char* key, std::string_view full) {\n"
        "    if (key == nullptr) {\n"
        "        return false;\n"
        "    }\n"
        "    const std::size_t dot = full.rfind('.');\n"
        "    const std::string_view name =\n"
        "        dot == std::string_view::npos ? full : full.substr(dot + 1u);\n"
        "    std::size_t index = 0;\n"
        "    while (key[index] != '\\0' && index < name.size()) {\n"
        "        const unsigned char left =\n"
        "            static_cast<unsigned char>(key[index]);\n"
        "        const unsigned char right =\n"
        "            static_cast<unsigned char>(name[index]);\n"
        "        if (std::tolower(left) != std::tolower(right)) {\n"
        "            return false;\n"
        "        }\n"
        "        ++index;\n"
        "    }\n"
        "    return key[index] == '\\0' && index == name.size();\n"
        "}\n"
        "\n"
        "}  // namespace\n"
        "\n"
        "const char* GeneratedModelRuntime::interop_parameter_string(\n"
        "    const char* name, std::size_t* length) const {\n"
        "    if (length != nullptr) {\n"
        "        *length = 0u;\n"
        "    }\n"
        + "\n".join(string_lines)
        + "\n"
        "    return nullptr;\n"
        "}\n"
        "\n"
        "bool GeneratedModelRuntime::interop_parameter_integer(\n"
        "    const char* name, std::int32_t* value) const {\n"
        + "\n".join(integer_lines)
        + "\n"
        "    return false;\n"
        "}\n"
        "\n"
    )


def _read_case(signal: Signal) -> str:
    return (
        f"        case {signal.value_reference}u:\n"
        + f"            out = {value_expression(signal)};\n"
        + "            return true;"
    )


def _write_case(signal: Signal) -> str:
    member = member_name(signal)
    if signal.data_type is DataType.STRING:
        assignment = (
            f"            copy_bounded({member}.data(), {member}.size(), "
            "value.string_value);"
        )
    elif signal.data_type is DataType.REAL:
        assignment = f"            {member} = value.real_value;"
    elif signal.data_type is DataType.INTEGER:
        assignment = f"            {member} = value.integer_value;"
    else:
        assignment = f"            {member} = value.boolean_value;"
    return (
        f"        case {signal.value_reference}u:\n"
        + f"            if (value.type != {cpp_data_type(signal)}) {{\n"
        + "                return false;\n"
        + "            }\n"
        + assignment
        + "\n"
        + "            return true;"
    )


def _render_model_impl(model: ModelDefinition) -> str:
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + "//\n"
        + "// User hook.  The SysML input defines the signal interface, not the\n"
        + "// equations, so the default implementation is deliberately empty.  Edit\n"
        + "// this file (only this file) to implement the model behaviour.\n"
        + "#pragma once\n"
        + "\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + "inline void user_step(GeneratedModelRuntime& model, double time, double dt) {\n"
        + "    (void)model;\n"
        + "    (void)time;\n"
        + "    (void)dt;\n"
        + "    // TODO: implement the model equations.  Read and write the typed\n"
        + "    // members declared in model_runtime.hpp.\n"
        + "}\n"
    )


def _render_bindings(model: ModelDefinition) -> str:
    outbound = [
        signal for signal in ordered_signals(model) if signal.direction is Direction.INPUT
    ]
    inbound = [
        signal
        for signal in ordered_signals(model)
        if signal.direction is Direction.OUTPUT
    ]
    publish_lines = "\n".join(_publish_signal(signal) for signal in outbound)
    consume_lines = "\n".join(_consume_signal(signal) for signal in inbound)
    if not publish_lines:
        publish_lines = "    // No FMI inputs to publish; the step time still travels."
    if not consume_lines:
        consume_lines = "    // No FMI outputs to consume."
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "//\n"
        + "// The wire direction is the inverse of FMI causality: FMI inputs are\n"
        + "// published outward and FMI outputs are consumed inward.  Parameters travel\n"
        + "// in neither direction and are not part of a frame.\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + "void GeneratedModelRuntime::publish(pyfmi_interop::Sample& sample) const {\n"
        + "    sample.simulation_time = m_simulation_time;\n"
        + publish_lines
        + "\n"
        + "}\n"
        + "\n"
        + "void GeneratedModelRuntime::consume(const pyfmi_interop::Sample& sample) {\n"
        + consume_lines
        + "\n"
        + "}\n"
    )


def _publish_signal(signal: Signal) -> str:
    vr = signal.value_reference
    return (
        f"    sample.values[{vr}] = {value_expression(signal)};\n"
        f"    sample.valid[{vr}] = 1u;"
    )


def _consume_signal(signal: Signal) -> str:
    vr = signal.value_reference
    member = member_name(signal)
    if signal.data_type is DataType.STRING:
        assignment = (
            f"        copy_bounded({member}.data(), {member}.size(),\n"
            f"                     sample.values[{vr}].string_value);"
        )
    elif signal.data_type is DataType.REAL:
        assignment = f"        {member} = sample.values[{vr}].real_value;"
    elif signal.data_type is DataType.INTEGER:
        assignment = f"        {member} = sample.values[{vr}].integer_value;"
    else:
        assignment = f"        {member} = sample.values[{vr}].boolean_value;"
    return (
        f"    if (sample.is_valid({vr}u)) {{\n"
        + assignment
        + "\n"
        + "    }"
    )


_CMAKELISTS_PREFIX = "# Generated by pyfmi-interop. Do not edit by hand.\n"
