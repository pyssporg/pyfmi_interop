"""The canonical protobuf payload backend.

The schema is a proto3 message whose field numbers are the IR value references
verbatim and whose field identifiers are the sanitized interface names.  It is
a shipped artifact, not an input to a build step; nothing here needs
``protoc``.

Moving this code out of :mod:`pyfmi_interop.schema` keeps the message emitter
and the C++ codec next to each other while ``schema.py`` remains the
backwards-compatible facade.
"""

from __future__ import annotations

from pathlib import Path

from ..ir import DataType, ModelDefinition, ProjectionError, Signal, fingerprint
from .base import Serialization, write_files
from .descriptor import SCHEMA_FORMAT_VERSION, WIRE_JSON_NAME, wire_json_bytes
from .naming import (
    field_identifiers,
    float_literal,
    member_name,
    message_identifier,
    string_literal,
    wire_signals,
)

__all__ = [
    "PROTO_PACKAGE",
    "SCHEMA_FORMAT_VERSION",
    "WIRE_JSON_NAME",
    "ProtobufSerialization",
    "backend",
    "payload_message_name",
    "proto_filename",
    "render_proto",
]

#: Proto package shared with the wire envelope.
PROTO_PACKAGE = "pyfmi_interop.wire"

#: The single value message every payload field references.
_VALUE_MESSAGE = """\
// One signal sample: exactly one member is set.  `string` carries UTF-8 bytes
// bounded by the signal capacity recorded on the payload field.
message Value {
  oneof kind {
    double real = 1;
    sint64 integer = 2;
    bool boolean = 3;
    bytes string = 4;
  }
}
"""

_HEADER = "// Generated by pyfmi-interop. Do not edit by hand.\n"


def proto_filename(model: ModelDefinition) -> str:
    """Return the payload schema filename for ``model``."""

    return f"{model.name}.proto"


def payload_message_name(model: ModelDefinition) -> str:
    """Return the payload message name: the part-definition/interface name."""

    return message_identifier(model.interface or model.name)


def _projected_signals(model: ModelDefinition) -> tuple[Signal, ...]:
    """Return wire signals in id order, rejecting what the wire cannot carry."""

    ordered = sorted(
        wire_signals(model), key=lambda item: (item.value_reference, item.name)
    )
    seen_ids: dict[int, str] = {}
    seen_names: set[str] = set()
    for signal in ordered:
        signal.check_projection()
        if signal.name in seen_names:
            raise ProjectionError("duplicate signal name", signal_name=signal.name)
        previous = seen_ids.get(signal.value_reference)
        if previous is not None:
            raise ProjectionError(
                f"duplicate value reference {signal.value_reference} "
                f"(also used by {previous!r})",
                signal_name=signal.name,
            )
        if signal.unit is not None and ("\n" in signal.unit or "\r" in signal.unit):
            raise ProjectionError(
                "unit must not contain line breaks", signal_name=signal.name
            )
        seen_ids[signal.value_reference] = signal.name
        seen_names.add(signal.name)
    # Raises ProjectionError on a sanitized-identifier collision.
    field_identifiers(model)
    return tuple(ordered)


def _comment_value(signal: Signal) -> str:
    rate = "base" if signal.rate_hz is None else f"{float_literal(signal.rate_hz)} Hz"
    if signal.unit is None:
        unit = "unspecified"
    elif signal.unit == "":
        unit = "dimensionless"
    else:
        unit = signal.unit
    return (
        f"name={signal.name} type={signal.data_type.value} "
        f"direction={signal.direction.value} rate={rate} unit={unit} "
        f"capacity={signal.wire_capacity}"
    )


def render_proto(model: ModelDefinition) -> str:
    """Return the deterministic proto3 payload schema for ``model``."""

    signals = _projected_signals(model)
    fields = field_identifiers(model)
    message = payload_message_name(model)
    lines = [
        "// Generated by pyfmi_interop. Do not edit by hand.",
        f"// Schema format version: {SCHEMA_FORMAT_VERSION}",
        f"// Model: {model.name}",
        f"// GUID: {model.guid}",
        f"// Model id: {_model_id_hex(model)}",
        "",
        'syntax = "proto3";',
        "",
        f"package {PROTO_PACKAGE};",
        "",
        _VALUE_MESSAGE,
        f'// Payload for one step of model "{model.name}".',
        f"message {message} {{",
        "  reserved 19000 to 19999;",
    ]
    if signals:
        lines.append("")
    for signal in signals:
        lines.append(f"  // {_comment_value(signal)}")
        lines.append(f"  Value {fields[signal.name]} = {signal.value_reference};")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _model_id_hex(model: ModelDefinition) -> str:
    from ..wire import model_id

    return model_id(model).hex()


class ProtobufSerialization(Serialization):
    """The canonical protobuf backend."""

    name = "protobuf"
    format_id = 1

    def payload_message(self, model: ModelDefinition) -> str:
        return payload_message_name(model)

    def proto_package(self, model: ModelDefinition) -> str | None:
        return PROTO_PACKAGE

    def cmake_proto_sources(self, model: ModelDefinition) -> tuple[str, ...]:
        return (proto_filename(model),)

    def schema_files(self, model: ModelDefinition) -> dict[str, bytes]:
        return {
            proto_filename(model): render_proto(model).encode("utf-8"),
            WIRE_JSON_NAME: wire_json_bytes(
                model, serialization=self.name, format_id=self.format_id
            ),
        }

    def generate_codec(
        self, model: ModelDefinition, out: str | Path, role: str
    ) -> list[Path]:
        files = {
            "model_wire.cpp": _render_model_wire(model),
            "wire_conformance.cpp": _render_wire_conformance(model),
        }
        return write_files(out, files)


# -- generated C++ codec ----------------------------------------------------

_VALUE_KIND = {
    DataType.REAL: (1, "SetDouble", "GetDouble"),
    DataType.INTEGER: (2, "SetInt64", "GetInt64"),
    DataType.BOOLEAN: (3, "SetBool", "GetBool"),
    DataType.STRING: (4, "SetString", "GetString"),
}


def _wire_encode_signal(signal: Signal) -> str:
    kind, setter, _getter = _VALUE_KIND[signal.data_type]
    member = member_name(signal)
    if signal.data_type is DataType.INTEGER:
        expression = f"static_cast<std::int64_t>({member})"
    elif signal.data_type is DataType.STRING:
        expression = f"std::string({member}.data(), bounded_length({member}))"
    else:
        expression = member
    return (
        "    {\n"
        "        const google::protobuf::FieldDescriptor* field =\n"
        f"            message.GetDescriptor()->FindFieldByNumber({signal.value_reference});\n"
        "        if (field == nullptr) {\n"
        f'            error = "payload field {signal.value_reference} is missing";\n'
        "            return false;\n"
        "        }\n"
        "        google::protobuf::Message* value =\n"
        "            message.GetReflection()->MutableMessage(&message, field);\n"
        "        const google::protobuf::FieldDescriptor* kind =\n"
        f"            value->GetDescriptor()->FindFieldByNumber({kind});\n"
        f"        value->GetReflection()->{setter}(value, kind, {expression});\n"
        "    }"
    )


def _wire_decode_signal(signal: Signal) -> str:
    kind, _setter, getter = _VALUE_KIND[signal.data_type]
    member = member_name(signal)
    if signal.data_type is DataType.STRING:
        assignment = (
            f"        copy_bounded({member}.data(), {member}.size(),\n"
            f"                     value.GetReflection()->{getter}(value, kind));"
        )
    elif signal.data_type is DataType.INTEGER:
        assignment = (
            f"        {member} = static_cast<std::int32_t>(\n"
            f"            value.GetReflection()->{getter}(value, kind));"
        )
    else:
        assignment = f"        {member} = value.GetReflection()->{getter}(value, kind);"
    return (
        "    {\n"
        f"        const google::protobuf::FieldDescriptor* field =\n"
        f"            message.GetDescriptor()->FindFieldByNumber({signal.value_reference});\n"
        "        if (field == nullptr) {\n"
        f'            error = "payload field {signal.value_reference} is missing";\n'
        "            return false;\n"
        "        }\n"
        "        const google::protobuf::Message& value =\n"
        "            message.GetReflection()->GetMessage(message, field);\n"
        "        const google::protobuf::FieldDescriptor* kind =\n"
        f"            value.GetDescriptor()->FindFieldByNumber({kind});\n"
        + assignment
        + "\n"
        "    }"
    )


def _render_model_wire(model: ModelDefinition) -> str:
    signals = wire_signals(model)
    proto_header = proto_filename(model).removesuffix(".proto") + ".pb.h"
    message = f"pyfmi_interop::wire::{payload_message_name(model)}"
    records = ", ".join(
        f"{{{signal.value_reference}u, {signal.data_type.number}u}}"
        for signal in signals
    )
    encode_lines = "\n".join(_wire_encode_signal(signal) for signal in signals)
    decode_lines = "\n".join(_wire_decode_signal(signal) for signal in signals)
    if not encode_lines:
        encode_lines = "    (void)message;"
    if not decode_lines:
        decode_lines = "    (void)message;"
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + f"// IR fingerprint: {fingerprint(model)}\n"
        + "//\n"
        + "// Payload layer for protobuf builds.  Signal values are mapped through\n"
        + "// the emitted <Model>Payload message with the protobuf reflection API; no\n"
        + "// protobuf byte layout is written by hand.  This translation unit is only\n"
        + "// compiled when PYFMI_INTEROP_WIRE=protobuf.\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + f'#include "{proto_header}"\n'
        + '#include "pyfmi_interop/runtime/wire.hpp"\n'
        + "\n"
        + "#include <array>\n"
        + "#include <cstddef>\n"
        + "#include <cstdint>\n"
        + "#include <limits>\n"
        + "#include <string>\n"
        + "#include <string_view>\n"
        + "#include <vector>\n"
        + "\n"
        + "namespace {\n"
        + "\n"
        + f"constexpr char kModelName[] = {string_literal(model.name)};\n"
        + "\n"
        + "template <std::size_t N>\n"
        + "std::size_t bounded_length(const std::array<char, N>& value) {\n"
        + "    std::size_t length = 0;\n"
        + "    while (length < N && value[length] != '\\0') {\n"
        + "        ++length;\n"
        + "    }\n"
        + "    return length;\n"
        + "}\n"
        + "\n"
        + "const std::array<std::uint8_t, pyfmi_interop::wire::kModelIdSize>& wire_model_id() {\n"
        + "    static const std::array<std::uint8_t, pyfmi_interop::wire::kModelIdSize> id =\n"
        + "        pyfmi_interop::wire::model_id(\n"
        + "            std::string_view(kModelName),\n"
        + "            std::vector<pyfmi_interop::wire::ModelIdSignal>{" + records + "});\n"
        + "    return id;\n"
        + "}\n"
        + "\n"
        + "}  // namespace\n"
        + "\n"
        + "bool GeneratedModelRuntime::encode_wire_payload(std::string& payload,\n"
        + "                                                std::string& error) const {\n"
        + f"    {message} message;\n"
        + encode_lines
        + "\n"
        + "    payload = message.SerializeAsString();\n"
        + "    if (payload.size() > std::numeric_limits<std::uint32_t>::max()) {\n"
        + '        error = "payload exceeds uint32 length";\n'
        + "        return false;\n"
        + "    }\n"
        + "    return true;\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::decode_wire_payload(std::string_view payload,\n"
        + "                                                std::string& error) {\n"
        + f"    {message} message;\n"
        + "    if (payload.size() >\n"
        + "        static_cast<std::size_t>(std::numeric_limits<int>::max())) {\n"
        + '        error = "payload is too large to parse";\n'
        + "        return false;\n"
        + "    }\n"
        + "    if (!message.ParseFromArray(payload.data(), static_cast<int>(payload.size()))) {\n"
        + '        error = "payload is not a valid ' + payload_message_name(model) + ' message";\n'
        + "        return false;\n"
        + "    }\n"
        + decode_lines
        + "\n"
        + "    return true;\n"
        + "}\n"
        + "\n"
        + "std::vector<std::uint8_t> GeneratedModelRuntime::encode_wire_frame(\n"
        + "    std::uint32_t instance, std::uint64_t sequence, std::uint64_t timestamp_ns,\n"
        + "    std::string& error) const {\n"
        + "    error.clear();\n"
        + "    std::string payload;\n"
        + "    if (!encode_wire_payload(payload, error)) {\n"
        + "        return {};\n"
        + "    }\n"
        + "    pyfmi_interop::wire::EncodeResult result = pyfmi_interop::wire::encode_frame(\n"
        + "        wire_model_id(), payload, instance, sequence, timestamp_ns,\n"
        + "        pyfmi_interop::wire::PayloadFormat::Protobuf);\n"
        + "    if (!result) {\n"
        + "        error = result.error.message;\n"
        + "        return {};\n"
        + "    }\n"
        + "    return std::move(result.frame);\n"
        + "}\n"
        + "\n"
        + "bool GeneratedModelRuntime::decode_wire_frame(\n"
        + "    const std::vector<std::uint8_t>& frame, std::string& error) {\n"
        + "    error.clear();\n"
        + "    const std::string_view buffer(\n"
        + "        reinterpret_cast<const char*>(frame.data()), frame.size());\n"
        + "    pyfmi_interop::wire::DecodeResult result =\n"
        + "        pyfmi_interop::wire::decode_frame(buffer);\n"
        + "    if (!result) {\n"
        + "        error = result.error.message;\n"
        + "        return false;\n"
        + "    }\n"
        + "    if (result.frame.header.model_id != wire_model_id()) {\n"
        + '        error = "model id mismatch";\n'
        + "        return false;\n"
        + "    }\n"
        + "    if (result.frame.header.payload_format !=\n"
        + "        pyfmi_interop::wire::PayloadFormat::Protobuf) {\n"
        + '        error = "payload format mismatch";\n'
        + "        return false;\n"
        + "    }\n"
        + "    const std::string_view payload(\n"
        + "        reinterpret_cast<const char*>(result.frame.payload.data()),\n"
        + "        result.frame.payload.size());\n"
        + "    return decode_wire_payload(payload, error);\n"
        + "}\n"
    )


def _render_wire_conformance(model: ModelDefinition) -> str:
    return (
        _HEADER
        + f"// Model: {model.name}\n"
        + "//\n"
        + "// Prints the hex of one wire frame encoded from the reset state.  The\n"
        + "// Python conformance test compares it with pyfmi_interop.wire.encode() over\n"
        + "// the same protobuf payload.\n"
        + '#include "model_runtime.hpp"\n'
        + "\n"
        + "#include <cstdio>\n"
        + "#include <string>\n"
        + "#include <vector>\n"
        + "\n"
        + "int main() {\n"
        + "    GeneratedModelRuntime model;\n"
        + "    model.reset();\n"
        + "    std::string error;\n"
        + "    const std::vector<std::uint8_t> frame =\n"
        + "        model.encode_wire_frame(7u, 42u, 1700000000000000000ULL, error);\n"
        + "    if (!error.empty() || frame.empty()) {\n"
        + '        std::fprintf(stderr, "wire encode failed: %s\\n", error.c_str());\n'
        + "        return 1;\n"
        + "    }\n"
        + "    for (const std::uint8_t byte : frame) {\n"
        + '        std::printf("%02x", byte);\n'
        + "    }\n"
        + '    std::printf("\\n");\n'
        + "    return 0;\n"
        + "}\n"
    )


backend = ProtobufSerialization()
