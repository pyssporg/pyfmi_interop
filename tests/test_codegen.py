EXPECTED_FILES = {
    "CMakeLists.txt",
    "bindings.cpp",
    "demo_model.proto",
    "model.json",
    "model_impl.hpp",
    "model_runtime.cpp",
    "model_runtime.hpp",
    "model_wire.cpp",
    "wire.json",
    "wire_conformance.cpp",
}


def make_model() -> ModelDefinition:
    signals = (
        Signal("speed", 1, DataType.REAL, Direction.OUTPUT, unit="m/s", initial=1.5),
        Signal("setpoint", 5, DataType.REAL, Direction.INPUT, rate_hz=50.0),
        Signal("label", 2, DataType.STRING, Direction.OUTPUT, capacity=16, initial="hi"),
        Signal("enable", 3, DataType.BOOLEAN, Direction.PARAMETER, initial=True),
        Signal("mode", 4, DataType.INTEGER, Direction.PARAMETER, initial=2),
    )
    bindings = (
        TransportBinding("speed", "hla", "Speed", Direction.OUTPUT),
        TransportBinding("setpoint", "dis", "Setpoint", Direction.INPUT),
        TransportBinding("label", "loopback", "Label", Direction.OUTPUT),
    )
    rate_groups = (RateGroup("fast", 0.02, 0.01, ("setpoint",)),)
    return ModelDefinition(
        name="demo_model",
        guid=deterministic_guid("demo_model"),
        step_size_s=0.01,
        signals=signals,
        bindings=bindings,
        rate_groups=rate_groups,
        description="codegen fixture",
    )


def test_generate_writes_self_contained_tree(tmp_path):
    target = generate_model(make_model(), tmp_path / "gen")

    assert target == tmp_path / "gen"
    assert {path.name for path in target.iterdir()} == EXPECTED_FILES
    assert (target / "model.json").read_text(encoding="utf-8").endswith("\n")


def test_generate_is_byte_deterministic(tmp_path):
    first = generate_model(make_model(), tmp_path / "first")
    second = generate_model(make_model(), tmp_path / "second")

    for name in sorted(EXPECTED_FILES):
        assert (first / name).read_bytes() == (second / name).read_bytes(), name


def test_generated_sources_carry_generator_header(tmp_path):
    target = generate_model(make_model(), tmp_path / "gen")

    for name in (
        "model_runtime.hpp",
        "model_runtime.cpp",
        "model_impl.hpp",
        "bindings.cpp",
        "model_wire.cpp",
        "wire_conformance.cpp",
    ):
        text = (target / name).read_text(encoding="utf-8")
        assert text.startswith("// Generated by pyfmi-interop"), name
    assert (target / "CMakeLists.txt").read_text(encoding="utf-8").startswith(
        "# Generated by pyfmi-interop"
    )


def test_descriptors_follow_value_reference_order(tmp_path):
    target = generate_model(make_model(), tmp_path / "gen")
    source = (target / "model_runtime.cpp").read_text(encoding="utf-8")

    assert "std::vector<pyfmi_interop::SignalDescriptor>" in source
    positions = [
        source.index(f'"{signal.name}", {signal.value_reference}u')
        for signal in sorted(make_model().signals, key=lambda item: item.value_reference)
    ]
    assert positions == sorted(positions)


