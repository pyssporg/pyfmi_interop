def test_invalid_ir_is_rejected(tmp_path):
    base = make_model()
    duplicate = ModelDefinition(
        name="bad_model",
        guid=deterministic_guid("bad_model"),
        step_size_s=0.01,
        signals=(
            Signal("same", 1, DataType.REAL, Direction.OUTPUT),
            Signal("same", 2, DataType.REAL, Direction.INPUT),
        ),
    )
    with pytest.raises(ValueError, match="duplicate signal names"):
        generate_model(duplicate, tmp_path / "duplicate")

    unknown_binding = ModelDefinition(
        name="bad_binding",
        guid=deterministic_guid("bad_binding"),
        step_size_s=base.step_size_s,
        signals=base.signals,
        bindings=(TransportBinding("missing", "hla", "x", Direction.OUTPUT),),
    )
    with pytest.raises(ValueError, match="unknown signal"):
        generate_model(unknown_binding, tmp_path / "binding")

    misaligned = ModelDefinition(
        name="bad_rate",
        guid=deterministic_guid("bad_rate"),
        step_size_s=0.01,
        signals=(Signal("x", 1, DataType.REAL, Direction.OUTPUT, rate_hz=30.0),),
    )
    with pytest.raises(ValueError, match="does not align"):
        generate_model(misaligned, tmp_path / "rate")


_CMAKE = shutil.which("cmake")


@pytest.mark.cpp
@pytest.mark.skipif(_CMAKE is None, reason="cmake is not available")
def test_generated_model_builds_with_native_runtime(tmp_path):
    repo_root = Path(__file__).resolve().parents[1]
    library = native.bundled_library_path()
    if not library.is_file():
        library = native.default_runtime_library_path(repo_root)
    if not library.is_file():
        pytest.skip("native runtime library has not been built")
    includes = native.runtime_include_dirs(repo_root)
    if not includes:
        pytest.skip("native runtime headers are not available")

    source = generate_model(make_model(), tmp_path / "gen")
    built = build_model(
        source,
        tmp_path / "build",
        runtime_library=library,
        runtime_include=includes[0],
    )

    assert built.is_file()

    cache = (tmp_path / "build" / "CMakeCache.txt").read_text(encoding="utf-8")
    assert "PYFMI_INTEROP_CMAKE_DIR:" in cache
    assert "PYFMI_INTEROP_SOURCE_DIR:" in cache

    nm = shutil.which("nm")
    if sys.platform.startswith("linux") and nm is not None:
        exported = subprocess.run(
            [nm, "-D", "--defined-only", str(built)],
            capture_output=True,
            text=True,
            check=True,
        ).stdout
        for symbol in (
            "fmi2Instantiate",
            "fmi2DoStep",
            "fmi2GetReal",
            "fmi2SetReal",
            "pyfmi_interop_create_model",
        ):
            assert symbol in exported, symbol
