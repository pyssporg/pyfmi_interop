"""A nested external proto tree compiles in one cold configure-and-build pass."""

from __future__ import annotations

import shutil
from pathlib import Path

import pytest

from pyfmi_interop import native
from pyfmi_interop.builder import build_model
from pyfmi_interop.codegen import generate_model
from pyfmi_interop.ir import (
    DataType,
    Direction,
    ModelDefinition,
    Signal,
    deterministic_guid,
)
from pyfmi_interop.serialization import register, registry
from pyfmi_interop.serialization.base import Serialization, write_files
from pyfmi_interop.serialization.descriptor import WIRE_JSON_NAME, wire_json_bytes

pytestmark = pytest.mark.component

_FIXTURE_ROOT = Path(__file__).resolve().parent / "fixtures" / "external_proto"
_PROTO_ROOT = _FIXTURE_ROOT / "proto"
_THING = _PROTO_ROOT / "acme" / "v1" / "thing.proto"
_EXTRA = _PROTO_ROOT / "acme" / "v1" / "extra.proto"

# The codec includes the root-relative header path, exactly as a consumer
# backend does; a basename-only output would leave this include unresolved.
_CODEC = """// Generated by pyfmi-interop
#include "acme/v1/extra.pb.h"
#include "acme/v1/thing.pb.h"

int acme_external_codec() {
    acme::v1::Thing thing;
    thing.set_value(1.0);
    thing.mutable_extra()->set_code(2);
    return thing.extra().code();
}
"""


def make_model() -> ModelDefinition:
    signals = (Signal("value", 1, DataType.REAL, Direction.OUTPUT, initial=0.0),)
    return ModelDefinition(
        name="acme_model",
        guid=deterministic_guid("acme_model"),
        step_size_s=0.01,
        signals=signals,
    )


class NestedExternalSerialization(Serialization):
    """A backend that keeps its proto tree outside the generated directory."""

    name = "acme_external"
    format_id = 11

    def __init__(self, root: Path, thing: Path, extra: Path) -> None:
        self.root = root
        self.thing = thing
        self.extra = extra

    def payload_message(self, model: ModelDefinition) -> str:
        return "acme.v1.Thing"

    def proto_package(self, model: ModelDefinition) -> str | None:
        return "acme.v1"

    def schema_files(self, model: ModelDefinition) -> dict[str, bytes]:
        return {
            WIRE_JSON_NAME: wire_json_bytes(
                model, serialization=self.name, format_id=self.format_id
            )
        }

    def generate_codec(
        self, model: ModelDefinition, out: str | Path, role: str
    ) -> list[Path]:
        return write_files(out, {"model_wire.cpp": _CODEC})

    def cmake_proto_sources(self, model: ModelDefinition) -> tuple[str, ...]:
        return (str(self.thing), str(self.extra))

    def cmake_proto_import_roots(self, model: ModelDefinition) -> tuple[str, ...]:
        return (str(self.root),)

    def cmake_include_dirs(self, model: ModelDefinition) -> tuple[str, ...]:
        return ()

    def cmake_link_libraries(self, model: ModelDefinition) -> tuple[str, ...]:
        return ("protobuf::libprotobuf",)


@pytest.fixture
def backend():
    instance = NestedExternalSerialization(_PROTO_ROOT, _THING, _EXTRA)
    register(instance)
    yield instance
    registry._BACKENDS.pop(instance.name, None)


_CMAKE = shutil.which("cmake")
_CPP = shutil.which("g++") or shutil.which("c++")
_PROTOC = shutil.which("protoc")


@pytest.mark.cpp
@pytest.mark.skipif(_CMAKE is None, reason="cmake is not available")
@pytest.mark.skipif(_CPP is None, reason="no C++ compiler is available")
@pytest.mark.skipif(_PROTOC is None, reason="protoc is not available")
def test_nested_external_proto_tree_builds_cold(tmp_path, backend):
    repo = Path(__file__).resolve().parents[1]
    library = native.bundled_library_path()
    if not library.is_file():
        library = native.default_runtime_library_path(repo)
    if not library.is_file():
        pytest.skip("native runtime library has not been built")
    includes = native.runtime_include_dirs(repo)
    if not includes:
        pytest.skip("native runtime headers are not available")

    source = generate_model(make_model(), tmp_path / "gen", serialization=backend.name)
    build_dir = tmp_path / "build"
    built = build_model(
        source,
        build_dir,
        runtime_library=library,
        runtime_include=includes[0],
        cmake_args=("-DPYFMI_INTEROP_WIRE=protobuf",),
    )

    assert built.is_file()
    proto_out = build_dir / "proto" / "acme" / "v1"
    assert (proto_out / "thing.pb.h").is_file()
    assert (proto_out / "extra.pb.h").is_file()
    # The import root is preserved, not collapsed to the proto's basename.
    assert not (build_dir / "proto" / "thing.pb.h").exists()
